const adapters=require("../match-sharing-adapters-v1.js");
const format=require("../match-sharing-format-v1.js");
const sender=require("../match-sharing-sender-v1.js");
const outputDirectory=path.resolve("outputs/match-sharing-stage4");
fs.mkdirSync(outputDirectory,{recursive:true});

const crcTable=Array.from({length:256},(_,value)=>{
  let crc=value;
  for(let bit=0;bit<8;bit+=1)crc=(crc&1)?0xedb88320^(crc>>>1):crc>>>1;
  return crc>>>0;
});
function crc32(buffer){
  let crc=0xffffffff;
  for(const value of buffer)crc=crcTable[(crc^value)&255]^(crc>>>8);
  return (crc^0xffffffff)>>>0;
}
function chunk(type,data){
  const name=Buffer.from(type),length=Buffer.alloc(4),check=Buffer.alloc(4);
  length.writeUInt32BE(data.length);check.writeUInt32BE(crc32(Buffer.concat([name,data])));
  return Buffer.concat([length,name,data,check]);
}
function qrPng(qrValue,modulePixels){
  const total=qrValue.size+qrValue.quietZone*2,width=total*modulePixels;
  const rows=Buffer.alloc((width*4+1)*width,255);
  for(let y=0;y<width;y+=1){
    const row=y*(width*4+1);rows[row]=0;
    for(let x=0;x<width;x+=1){
      const moduleX=Math.floor(x/modulePixels)-qrValue.quietZone,moduleY=Math.floor(y/modulePixels)-qrValue.quietZone;
      const dark=qrValue.matrix.getModule(moduleX,moduleY),offset=row+1+x*4,value=dark?0:255;
      rows[offset]=value;rows[offset+1]=value;rows[offset+2]=value;rows[offset+3]=255;
    }
  }
  const header=Buffer.alloc(13);header.writeUInt32BE(width,0);header.writeUInt32BE(width,4);header[8]=8;header[9]=6;
  return {width,buffer:Buffer.concat([Buffer.from("89504e470d0a1a0a","hex"),chunk("IHDR",header),chunk("IDAT",zlib.deflateSync(rows,{level:9})),chunk("IEND",Buffer.alloc(0))])};
}

const all=[];
for(const fixture of stage1Fixtures()){
  const logical=adapters.buildSharedMatchV1(fixture.source,{sharedMatchId:fixture.sharedMatchId});
  const compact=adapters.compactSharedMatchV1(logical);
  const payload=await format.encodeSharedMatchV1(logical,sender.runtimeCodec);
  const qr=sender.createQr(payload),envelope=format.base45Decode(payload.slice(format.PREFIX.length));
  all.push({fixture,logical,compact,payload,qr,compressedBytes:envelope.length-format.HEADER_BYTES-format.DIGEST_BYTES});
}
const choices=[
  ["A","Light",item=>item.fixture.fixtureId==="sample-match-0372"],
  ["B","Medium",item=>item.fixture.fixtureId==="sample-match-0796"],
  ["C","Heavy",item=>item.fixture.fixtureId==="sample-match-0633"],
];
const evidence=[];
for(const [caseId,weight,predicate] of choices){
  const selected=all.find(predicate);if(!selected)throw new Error(`Missing ${caseId} fixture`);
  const totalModules=selected.qr.size+selected.qr.quietZone*2;
  const modulePixels=Math.max(1,Math.floor((sender.DISPLAY_SIZE_PT*3)/totalModules));
  const png=qrPng(selected.qr,modulePixels);
  const fileName=`MatchSharing_Production_QR_${caseId}_${weight}.png`;
  fs.writeFileSync(path.join(outputDirectory,fileName),png.buffer);
  evidence.push({
    case:caseId,weight,discipline:selected.fixture.label,lengthClass:selected.fixture.lengthClass,
    fixtureId:selected.fixture.fixtureId,sourceRecordBytes:Buffer.byteLength(JSON.stringify(selected.fixture.source)),
    compactBytes:Buffer.byteLength(format.stableStringify(selected.compact)),compressedBytes:selected.compressedBytes,
    csm1Characters:selected.payload.length,qrVersion:selected.qr.version,moduleCount:selected.qr.size,
    quietZoneModules:selected.qr.quietZone,totalModules,ecc:selected.qr.ecc,
    productionDisplayPt:sender.DISPLAY_SIZE_PT,evidencePngPixels:png.width,modulePixels,file:fileName,
  });
}
fs.writeFileSync(path.join(outputDirectory,"MatchSharing_Stage4_QR_Evidence.json"),`${JSON.stringify({generatedAt:"2026-09-28",generator:"CueScoreMatchSharingSenderV1 production runtime",cases:evidence},null,2)}\n`);
const rows=evidence.map(item=>`| ${item.case} | ${item.discipline} ${item.lengthClass} | ${item.fixtureId} | ${item.csm1Characters} | ${item.qrVersion} | ${item.moduleCount}×${item.moduleCount} | ${item.ecc} | ${item.productionDisplayPt}pt | [PNG](./${item.file}) |`).join("\n");
